"""Generate offline corrective-action suggestions from the original report templates."""
import json
from pathlib import Path
import re
from docx import Document

ROOT=Path(__file__).resolve().parents[1]


def extract_actions():
    actions={'SF':[],'SH':[],'OT':[]}
    for name in ('Full','SF-Ois','SH-Ois'):
        for table in Document(ROOT/'templates'/('New Template '+name+'.docx')).tables:
            equipment=None
            for row in table.rows:
                cells=[cell.text.strip() for cell in row.cells]
                heading=next((s for s in cells if s.startswith('Section 4') and 'Open Items' in s),None)
                if heading:
                    equipment='SF' if 'Scaffold' in heading else 'SH' if 'Shed' in heading else 'OT'
                    continue
                if not equipment or len(cells)<3:continue
                # Grid-cell aliases may repeat merged values, but the final cell is the action.
                action=re.sub(r'\s+',' ',cells[-1]).strip()
                if not action or action=='Action' or 'CUSTOM VERBIAGE' in action.upper():continue
                if action not in actions[equipment]:actions[equipment].append(action)
    return actions


def build():
    actions=extract_actions()
    (ROOT/'backend/web/action-options.js').write_text('// Generated by scripts/build_action_options.py; suggestions require inspector selection.\nconst actionSuggestions = '+json.dumps(actions,ensure_ascii=False,indent=2)+';\n')
    source='// Generated by scripts/build_action_options.py from original templates.\nimport Foundation\n\nenum CorrectionOptions {\n    static let byEquipment: [String: [String]] = [\n'
    for key,values in actions.items():
        source+='        '+json.dumps(key)+': [\n'
        source+=''.join('            '+json.dumps(value,ensure_ascii=False)+',\n' for value in values)
        source+='        ],\n'
    source+='    ]\n}\n'
    (ROOT/'ios/JBIInspections/CorrectionOptions.swift').write_text(source)
    return actions

if __name__=='__main__':print({key:len(values) for key,values in build().items()})
